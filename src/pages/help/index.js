function renderHeader() {
  return `
    <header class="help-header">
      <a class="help-header__utility" href="#menu">к меню</a>
      <a class="help-header__utility" href="#help">помощь</a>
    </header>
  `
}

function renderChoice() {
  return `
    <main class="help help--choice">
      <section class="help-stage" aria-labelledby="help-choice-title">
        ${renderHeader()}
        <div class="help-stage__ellipse" aria-hidden="true"></div>
        <div class="help-choice">
          <a class="help-back" href="#menu" aria-label="Вернуться в меню">←</a>
          <h1 id="help-choice-title">выберите, какая<br>помощь нужна сейчас</h1>
          <p>Здесь собраны бережные шаги, которые могут помочь в разговоре, вопросах денег и заботе о себе.</p>
          <div class="help-choice__filters" role="group" aria-label="Выберите тему помощи">
            ${topics.map((topic) => `<button class="help-filter" type="button" data-select-topic="${topic.id}">${topic.label}</button>`).join('')}
          </div>
        </div>
      </section>
    </main>
  `
}

function renderArticle(topic) {
  return `
    <main class="help help--article">
      <section class="help-stage" aria-labelledby="help-title">
        ${renderHeader()}
        <div class="help-stage__ellipse" aria-hidden="true"></div>
        <div class="help-article__topline">
          <button class="help-back help-back--light" type="button" data-back-choice aria-label="Вернуться к выбору">←</button>
          <span>${topic.shortLabel}</span>
        </div>
        <header class="help-article__hero">
          <h1 id="help-title">${topic.title}</h1>
          <p>${topic.lead}</p>
        </header>
      </section>
      <article class="help-article" aria-label="Материал: ${topic.title}">
        ${topic.sections.map((section) => `
          <section class="help-article__section">
            <h2>${section.heading}</h2>
            ${section.quote ? `<blockquote>${section.quote}</blockquote>` : ''}
            ${(section.paragraphs ?? []).map((paragraph) => `<p>${paragraph}</p>`).join('')}
            ${section.list ? `<ul>${section.list.map((item) => `<li>${item}</li>`).join('')}</ul>` : ''}
          </section>
        `).join('')}
        <aside class="help-urgent">
          <h2>если небезопасно</h2>
          <p>Если есть непосредственная угроза жизни или безопасности, звоните 112. За срочной психологической поддержкой можно обратиться в <a href="https://psi.mchs.gov.ru/" target="_blank" rel="noreferrer">службу МЧС России</a>: +7 (495) 989-50-50.</p>
        </aside>
      </article>
    </main>
  `
}

export function renderHelpPage(app) {
  let activeTopic = topics[0]
  let screen = 'choice'

  const render = () => {
    app.innerHTML = screen === 'article' ? renderArticle(activeTopic) : renderChoice()

    app.querySelector('[data-back-choice]')?.addEventListener('click', () => {
      screen = 'choice'
      render()
    })

    app.querySelectorAll('[data-select-topic]').forEach((button) => {
      button.addEventListener('click', () => {
        activeTopic = topics.find((topic) => topic.id === button.dataset.selectTopic)
        screen = 'article'
        render()
      })
    })
  }

  render()
}
